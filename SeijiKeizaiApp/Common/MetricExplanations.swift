import Foundation

/// 画面に出る指標の定義文。
///
/// 同じ指標が複数の画面に出るため文言を1か所にまとめている。
/// 定義が分からない数字は、良くなったのか悪くなったのかを判断できず、
/// かえって学習の妨げになるため、すべての指標に説明を用意する方針にしている。
enum MetricExplanations {
    static let todayAccuracy = """
    今日解答した問題のうち、正解した割合です。

    同じ問題を複数回解いた場合は、その回数分すべてを数えます。
    """

    static let todayStudied = """
    今日解答した問題数です。同じ問題を複数回解いた場合はその都度数えます。
    """

    static let overallAccuracy = """
    これまでの全解答のうち、正解した割合です。出題されたことのある問題だけを対象にしています。

    復習で解き直した分も含むため、苦手な問題を繰り返すと一時的に下がることがあります。
    """

    static let mastery = """
    問題ごとの習熟段階です。直近の正誤ではなく、間隔をあけて解けたかどうかで判定します。

    ・未学習 … まだ一度も出題されていない
    ・要復習 … 直近で間違えた、または復習期限が来ている
    ・学習中 … 正解を重ねている途中（1〜3日間隔で再出題）
    ・習得済み … 1週間以上あけても正解できた

    正解するたびに復習の間隔が 1日 → 3日 → 7日 → 14日 → 30日 と伸び、間違えると最短に戻ります。

    「習得済み」は7日以上の間隔に到達した問題です。直前に1回正解しただけでは「学習中」までで、\
    本番では解けない問題を習得扱いにしないようにしています。
    """

    static let dueForReview = """
    復習の期限が来ている問題の数です。間違えた問題はその日のうちに、正解した問題は習熟段階に応じた日数をあけて、再び出題対象になります。
    """

    static let streak = """
    連続して学習した日数です。1問でも解答した日を「学習した日」として数えます。

    今日まだ解答していなくても、前日までの記録は途切れたことにしません。
    """

    /// 分野別習熟度。配点の比重が分野ごとに違うため、全体の数字より行動を決めやすい。
    static let fieldMastery = """
    分野ごとの習得済みの割合です。

    「公共，政治・経済」は『公共』からおよそ4分の1、残りが『政治・経済』から出題されます。\
    本アプリでは政治・経済をさらに「政治」「経済」「国際」に分けて集計しています。\
    経済分野は用語どうしの因果（金利・物価・為替・景気）がつながっており、\
    1つの穴が複数の問題に響きやすい分野です。

    全体の習熟度より、いちばん低い分野をどれだけ引き上げられているかが目安になります。
    """
}
